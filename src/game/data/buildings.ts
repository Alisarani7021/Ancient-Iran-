import type { BuildingDef, BuildingLevel, Resources } from "../types";

type R = Partial<Resources>;

/** Generate 3 levels scaling cost and output. */
function levels(
  base: { cost: R; production?: R; storage?: R; housing?: number; workers?: number; prestige?: number; stability?: number },
  costMult = 1.9,
  outMult = 1.6,
): BuildingLevel[] {
  const out: BuildingLevel[] = [];
  for (let i = 0; i < 3; i++) {
    const cm = Math.pow(costMult, i);
    const om = Math.pow(outMult, i);
    const scale = (r?: R) =>
      r ? (Object.fromEntries(Object.entries(r).map(([k, v]) => [k, Math.round((v ?? 0) * om)])) as R) : undefined;
    out.push({
      cost: Object.fromEntries(Object.entries(base.cost).map(([k, v]) => [k, Math.round((v ?? 0) * cm)])) as R,
      production: scale(base.production),
      storage: scale(base.storage),
      housing: base.housing ? Math.round(base.housing * om) : undefined,
      workers: base.workers ? Math.round(base.workers * (1 + i * 0.4)) : undefined,
      prestige: base.prestige ? Math.round(base.prestige * om) : undefined,
      stability: base.stability ? base.stability + i : undefined,
    });
  }
  return out;
}

